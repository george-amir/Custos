use crate::config::FirewallConfig;
use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};
use std::net::IpAddr;
use std::process::Command;
use std::sync::Mutex;
use std::sync::atomic::{AtomicU64, Ordering};
use tracing::{debug, info, warn};

/// Cross-platform OS firewall backends supported by JevSec.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum FirewallBackend {
    /// Automatically selects `pf` on macOS/BSD, `nftables` on Linux, and `windows_netsh` on Windows.
    Auto,
    /// Linux netfilter `nftables` (`nft` CLI) with native per-IP kernel timeouts.
    Nftables,
    /// Linux `ipset` (`ipset` CLI) with native per-IP kernel timeouts.
    Ipset,
    /// macOS / FreeBSD / OpenBSD Packet Filter (`pfctl -t <table_name>`).
    Pf,
    /// Windows Advanced Firewall (`netsh advfirewall firewall`).
    WindowsNetsh,
}

impl FirewallBackend {
    /// Resolves `FirewallBackend::Auto` to the current host operating system's native firewall.
    pub fn resolve(self) -> Self {
        match self {
            Self::Auto => {
                if cfg!(target_os = "linux") {
                    Self::Nftables
                } else if cfg!(any(
                    target_os = "macos",
                    target_os = "freebsd",
                    target_os = "openbsd",
                    target_os = "netbsd"
                )) {
                    Self::Pf
                } else if cfg!(target_os = "windows") {
                    Self::WindowsNetsh
                } else {
                    Self::Pf
                }
            }
            explicit => explicit,
        }
    }

    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Auto => "auto",
            Self::Nftables => "nftables",
            Self::Ipset => "ipset",
            Self::Pf => "pf",
            Self::WindowsNetsh => "windows_netsh",
        }
    }
}

/// A single OS command specification generated by the cross-platform firewall translator.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FirewallCommandSpec {
    pub program: String,
    pub args: Vec<String>,
}

impl FirewallCommandSpec {
    pub fn new(program: &str, args: impl IntoIterator<Item = impl Into<String>>) -> Self {
        Self {
            program: program.to_string(),
            args: args.into_iter().map(Into::into).collect(),
        }
    }

    pub fn to_shell_string(&self) -> String {
        format!("{} {}", self.program, self.args.join(" "))
    }
}

#[derive(Debug, Default)]
pub struct FirewallMetrics {
    pub rules_applied: AtomicU64,
    pub rules_removed: AtomicU64,
    pub command_errors: AtomicU64,
}

/// Cross-platform OS firewall bouncer that translates IP ban/unban decisions into
/// native kernel firewall commands (`nft`, `ipset`, `pfctl`, or `netsh`).
pub struct FirewallBouncer {
    cfg: FirewallConfig,
    resolved_backend: FirewallBackend,
    recent_commands: Mutex<Vec<String>>,
    pub metrics: FirewallMetrics,
}

impl FirewallBouncer {
    pub fn new(cfg: FirewallConfig) -> Self {
        let resolved_backend = cfg.backend.resolve();
        Self {
            cfg,
            resolved_backend,
            recent_commands: Mutex::new(Vec::new()),
            metrics: FirewallMetrics::default(),
        }
    }

    pub fn resolved_backend(&self) -> FirewallBackend {
        self.resolved_backend
    }

    pub fn is_enabled(&self) -> bool {
        self.cfg.enabled
    }

    pub fn is_dry_run(&self) -> bool {
        self.cfg.dry_run
    }

    pub fn recent_commands(&self) -> Vec<String> {
        self.recent_commands
            .lock()
            .map(|g| g.clone())
            .unwrap_or_default()
    }

    /// Initializes the underlying OS firewall table/set if needed.
    pub fn init_backend(&self) -> Result<Vec<String>> {
        if !self.cfg.enabled {
            return Ok(Vec::new());
        }
        let specs = self.build_init_commands();
        self.execute_specs(&specs)
    }

    /// Blocks `ip` at the OS firewall level for `ttl_secs`.
    pub fn ban_ip(&self, ip: IpAddr, ttl_secs: u64) -> Result<String> {
        if !self.cfg.enabled {
            return Ok(String::new());
        }
        let spec = self.build_ban_command(ip, ttl_secs);
        self.execute_specs(std::slice::from_ref(&spec))?;
        self.metrics.rules_applied.fetch_add(1, Ordering::Relaxed);
        Ok(spec.to_shell_string())
    }

    /// Blocks a slice of `(IpAddr, ttl_secs)` entries in a single batched OS firewall
    /// command where supported (`pfctl` and `nftables`), eliminating per-IP process spawn overhead.
    pub fn ban_ips_batch(&self, entries: &[(IpAddr, u64)]) -> Result<Vec<String>> {
        if !self.cfg.enabled || entries.is_empty() {
            return Ok(Vec::new());
        }
        let specs = self.build_batch_ban_commands(entries);
        let out = self.execute_specs(&specs)?;
        self.metrics
            .rules_applied
            .fetch_add(entries.len() as u64, Ordering::Relaxed);
        Ok(out)
    }

    /// Pure function that packs multiple `(IpAddr, ttl_secs)` entries into minimal OS commands.
    pub fn build_batch_ban_commands(&self, entries: &[(IpAddr, u64)]) -> Vec<FirewallCommandSpec> {
        if entries.is_empty() {
            return Vec::new();
        }
        let table = &self.cfg.table_name;
        match self.resolved_backend {
            FirewallBackend::Pf | FirewallBackend::Auto => {
                // `pfctl -t <table> -T add ip1 ip2 ip3 ...` accepts all IPs in one call
                let mut args = vec![
                    "-t".to_string(),
                    table.clone(),
                    "-T".to_string(),
                    "add".to_string(),
                ];
                for (ip, _) in entries {
                    args.push(ip.to_string());
                }
                vec![FirewallCommandSpec::new("pfctl", args)]
            }
            FirewallBackend::Nftables => {
                let mut v4_elems = Vec::new();
                let mut v6_elems = Vec::new();
                for (ip, ttl) in entries {
                    let t = (*ttl).max(1);
                    if ip.is_ipv4() {
                        v4_elems.push(format!("{ip} timeout {t}s"));
                    } else {
                        v6_elems.push(format!("{ip} timeout {t}s"));
                    }
                }
                let mut specs = Vec::new();
                if !v4_elems.is_empty() {
                    let set_expr = format!("{{ {} }}", v4_elems.join(", "));
                    specs.push(FirewallCommandSpec::new(
                        "nft",
                        ["add", "element", "inet", table, "block_v4", &set_expr],
                    ));
                }
                if !v6_elems.is_empty() {
                    let set_expr = format!("{{ {} }}", v6_elems.join(", "));
                    specs.push(FirewallCommandSpec::new(
                        "nft",
                        ["add", "element", "inet", table, "block_v6", &set_expr],
                    ));
                }
                specs
            }
            FirewallBackend::Ipset | FirewallBackend::WindowsNetsh => entries
                .iter()
                .map(|(ip, ttl)| self.build_ban_command(*ip, *ttl))
                .collect(),
        }
    }

    /// Removes `ip` from the OS firewall table/set.
    pub fn unban_ip(&self, ip: IpAddr) -> Result<String> {
        if !self.cfg.enabled {
            return Ok(String::new());
        }
        let spec = self.build_unban_command(ip);
        self.execute_specs(std::slice::from_ref(&spec))?;
        self.metrics.rules_removed.fetch_add(1, Ordering::Relaxed);
        Ok(spec.to_shell_string())
    }

    /// Pure function that constructs the initialization commands for the resolved OS backend.
    pub fn build_init_commands(&self) -> Vec<FirewallCommandSpec> {
        let table = &self.cfg.table_name;
        match self.resolved_backend {
            FirewallBackend::Nftables => vec![
                FirewallCommandSpec::new("nft", ["add", "table", "inet", table]),
                FirewallCommandSpec::new(
                    "nft",
                    [
                        "add",
                        "set",
                        "inet",
                        table,
                        "block_v4",
                        "{ type ipv4_addr; flags timeout; }",
                    ],
                ),
                FirewallCommandSpec::new(
                    "nft",
                    [
                        "add",
                        "set",
                        "inet",
                        table,
                        "block_v6",
                        "{ type ipv6_addr; flags timeout; }",
                    ],
                ),
                FirewallCommandSpec::new(
                    "nft",
                    [
                        "add",
                        "chain",
                        "inet",
                        table,
                        "input",
                        "{ type filter hook input priority -10; policy accept; }",
                    ],
                ),
                FirewallCommandSpec::new(
                    "nft",
                    [
                        "add",
                        "rule",
                        "inet",
                        table,
                        "input",
                        "ip",
                        "saddr",
                        "@block_v4",
                        "drop",
                    ],
                ),
                FirewallCommandSpec::new(
                    "nft",
                    [
                        "add",
                        "rule",
                        "inet",
                        table,
                        "input",
                        "ip6",
                        "saddr",
                        "@block_v6",
                        "drop",
                    ],
                ),
            ],
            FirewallBackend::Ipset => vec![
                FirewallCommandSpec::new(
                    "ipset",
                    [
                        "create",
                        &format!("{table}_v4"),
                        "hash:ip",
                        "family",
                        "inet",
                        "timeout",
                        "3600",
                        "-exist",
                    ],
                ),
                FirewallCommandSpec::new(
                    "ipset",
                    [
                        "create",
                        &format!("{table}_v6"),
                        "hash:ip",
                        "family",
                        "inet6",
                        "timeout",
                        "3600",
                        "-exist",
                    ],
                ),
            ],
            FirewallBackend::Pf | FirewallBackend::Auto => {
                // pf tables are created on demand when adding the first IP via `pfctl -t <table> -T add`
                Vec::new()
            }
            FirewallBackend::WindowsNetsh => Vec::new(),
        }
    }

    /// Pure function that builds the exact OS firewall command to block `ip` for `ttl_secs`.
    pub fn build_ban_command(&self, ip: IpAddr, ttl_secs: u64) -> FirewallCommandSpec {
        let table = &self.cfg.table_name;
        let ttl = ttl_secs.max(1);
        match self.resolved_backend {
            FirewallBackend::Nftables => {
                let set_name = if ip.is_ipv4() { "block_v4" } else { "block_v6" };
                let elem = format!("{{ {} timeout {}s }}", ip, ttl);
                FirewallCommandSpec::new("nft", ["add", "element", "inet", table, set_name, &elem])
            }
            FirewallBackend::Ipset => {
                let set_name = if ip.is_ipv4() {
                    format!("{table}_v4")
                } else {
                    format!("{table}_v6")
                };
                FirewallCommandSpec::new(
                    "ipset",
                    [
                        "add",
                        &set_name,
                        &ip.to_string(),
                        "timeout",
                        &ttl.to_string(),
                        "-exist",
                    ],
                )
            }
            FirewallBackend::Pf | FirewallBackend::Auto => {
                FirewallCommandSpec::new("pfctl", ["-t", table, "-T", "add", &ip.to_string()])
            }
            FirewallBackend::WindowsNetsh => {
                let rule_name = format!("name=Custos-Block-{}", ip);
                let remote_ip = format!("remoteip={}", ip);
                FirewallCommandSpec::new(
                    "netsh",
                    [
                        "advfirewall",
                        "firewall",
                        "add",
                        "rule",
                        &rule_name,
                        "dir=in",
                        "action=block",
                        &remote_ip,
                    ],
                )
            }
        }
    }

    /// Pure function that builds the exact OS firewall command to unblock `ip`.
    pub fn build_unban_command(&self, ip: IpAddr) -> FirewallCommandSpec {
        let table = &self.cfg.table_name;
        match self.resolved_backend {
            FirewallBackend::Nftables => {
                let set_name = if ip.is_ipv4() { "block_v4" } else { "block_v6" };
                let elem = format!("{{ {} }}", ip);
                FirewallCommandSpec::new(
                    "nft",
                    ["delete", "element", "inet", table, set_name, &elem],
                )
            }
            FirewallBackend::Ipset => {
                let set_name = if ip.is_ipv4() {
                    format!("{table}_v4")
                } else {
                    format!("{table}_v6")
                };
                FirewallCommandSpec::new("ipset", ["del", &set_name, &ip.to_string(), "-exist"])
            }
            FirewallBackend::Pf | FirewallBackend::Auto => {
                FirewallCommandSpec::new("pfctl", ["-t", table, "-T", "delete", &ip.to_string()])
            }
            FirewallBackend::WindowsNetsh => {
                let rule_name = format!("name=Custos-Block-{}", ip);
                FirewallCommandSpec::new(
                    "netsh",
                    ["advfirewall", "firewall", "delete", "rule", &rule_name],
                )
            }
        }
    }

    fn execute_specs(&self, specs: &[FirewallCommandSpec]) -> Result<Vec<String>> {
        let mut executed = Vec::with_capacity(specs.len());

        for spec in specs {
            let cmd_str = spec.to_shell_string();
            self.record_command(&cmd_str);

            if self.cfg.dry_run {
                info!(
                    backend = self.resolved_backend.as_str(),
                    dry_run = true,
                    command = %cmd_str,
                    "Simulated OS firewall rule"
                );
                executed.push(cmd_str);
                continue;
            }

            debug!(
                backend = self.resolved_backend.as_str(),
                command = %cmd_str,
                "Executing live OS firewall command"
            );

            let output = Command::new(&spec.program)
                .args(&spec.args)
                .output()
                .with_context(|| format!("Failed to spawn firewall binary `{}`", spec.program));

            match output {
                Ok(out) if out.status.success() => {
                    info!(
                        backend = self.resolved_backend.as_str(),
                        command = %cmd_str,
                        "Enforced live OS firewall rule"
                    );
                    executed.push(cmd_str);
                }
                Ok(out) => {
                    self.metrics.command_errors.fetch_add(1, Ordering::Relaxed);
                    let stderr = String::from_utf8_lossy(&out.stderr);
                    warn!(
                        backend = self.resolved_backend.as_str(),
                        command = %cmd_str,
                        status = %out.status,
                        stderr = %stderr.trim(),
                        "OS firewall command returned non-zero status (ensure custos runs with root/Administrator privileges or set firewall.dry_run = true)"
                    );
                }
                Err(err) => {
                    self.metrics.command_errors.fetch_add(1, Ordering::Relaxed);
                    warn!(
                        backend = self.resolved_backend.as_str(),
                        command = %cmd_str,
                        error = %err,
                        "Failed to invoke OS firewall command"
                    );
                }
            }
        }

        Ok(executed)
    }

    fn record_command(&self, cmd: &str) {
        if let Ok(mut guard) = self.recent_commands.lock() {
            if guard.len() >= 100 {
                guard.remove(0);
            }
            guard.push(cmd.to_string());
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn test_cfg(backend: FirewallBackend) -> FirewallConfig {
        FirewallConfig {
            enabled: true,
            backend,
            dry_run: true,
            table_name: "custos_block".to_string(),
        }
    }

    #[test]
    fn test_cross_platform_command_generation_linux_nftables() {
        let fw = FirewallBouncer::new(test_cfg(FirewallBackend::Nftables));
        let ip4: IpAddr = "198.51.100.44".parse().unwrap();
        let ip6: IpAddr = "2001:db8::dead:beef".parse().unwrap();

        let ban4 = fw.build_ban_command(ip4, 3600);
        assert_eq!(
            ban4.to_shell_string(),
            "nft add element inet custos_block block_v4 { 198.51.100.44 timeout 3600s }"
        );

        let ban6 = fw.build_ban_command(ip6, 1800);
        assert_eq!(
            ban6.to_shell_string(),
            "nft add element inet custos_block block_v6 { 2001:db8::dead:beef timeout 1800s }"
        );

        let unban4 = fw.build_unban_command(ip4);
        assert_eq!(
            unban4.to_shell_string(),
            "nft delete element inet custos_block block_v4 { 198.51.100.44 }"
        );
    }

    #[test]
    fn test_cross_platform_command_generation_macos_bsd_pf() {
        let fw = FirewallBouncer::new(test_cfg(FirewallBackend::Pf));
        let ip: IpAddr = "203.0.113.88".parse().unwrap();

        let ban = fw.build_ban_command(ip, 3600);
        assert_eq!(
            ban.to_shell_string(),
            "pfctl -t custos_block -T add 203.0.113.88"
        );

        let unban = fw.build_unban_command(ip);
        assert_eq!(
            unban.to_shell_string(),
            "pfctl -t custos_block -T delete 203.0.113.88"
        );
    }

    #[test]
    fn test_cross_platform_command_generation_linux_ipset_and_windows_netsh() {
        let fw_ipset = FirewallBouncer::new(test_cfg(FirewallBackend::Ipset));
        let ip: IpAddr = "198.51.100.99".parse().unwrap();
        assert_eq!(
            fw_ipset.build_ban_command(ip, 600).to_shell_string(),
            "ipset add custos_block_v4 198.51.100.99 timeout 600 -exist"
        );

        let fw_win = FirewallBouncer::new(test_cfg(FirewallBackend::WindowsNetsh));
        assert_eq!(
            fw_win.build_ban_command(ip, 600).to_shell_string(),
            "netsh advfirewall firewall add rule name=Custos-Block-198.51.100.99 dir=in action=block remoteip=198.51.100.99"
        );
        assert_eq!(
            fw_win.build_unban_command(ip).to_shell_string(),
            "netsh advfirewall firewall delete rule name=Custos-Block-198.51.100.99"
        );
    }

    #[test]
    fn test_batch_ban_command_packing_pf_and_nftables() {
        let entries: Vec<(IpAddr, u64)> = vec![
            ("198.51.100.44".parse().unwrap(), 3600),
            ("203.0.113.88".parse().unwrap(), 3600),
        ];

        let fw_pf = FirewallBouncer::new(test_cfg(FirewallBackend::Pf));
        let pf_cmds = fw_pf.build_batch_ban_commands(&entries);
        assert_eq!(pf_cmds.len(), 1);
        assert_eq!(
            pf_cmds[0].to_shell_string(),
            "pfctl -t custos_block -T add 198.51.100.44 203.0.113.88"
        );

        let fw_nft = FirewallBouncer::new(test_cfg(FirewallBackend::Nftables));
        let nft_cmds = fw_nft.build_batch_ban_commands(&entries);
        assert_eq!(nft_cmds.len(), 1);
        assert_eq!(
            nft_cmds[0].to_shell_string(),
            "nft add element inet custos_block block_v4 { 198.51.100.44 timeout 3600s, 203.0.113.88 timeout 3600s }"
        );
    }
}
